import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

// Maintainer-only generation from an explicitly selected canonical checkout.
// No runtime download, workspace discovery, or upstream source distribution.
try {
  const [checkout, revision, mode] = process.argv.slice(2);
  if (!checkout || !/^[a-f0-9]{40}$/.test(revision ?? "") || (mode && mode !== "--check")) {
    throw new Error(
      "Usage: node scripts/pin-helper.mjs CANONICAL_CHECKOUT FULL_REVISION [--check]",
    );
  }
  const sourcePath = "skills/autoreview/scripts/autoreview";
  const bytes = execFileSync("git", ["-C", checkout, "show", `${revision}:${sourcePath}`], {
    maxBuffer: 1024 * 1024,
    env: { ...process.env, GIT_NO_LAZY_FETCH: "1" },
  });
  const metadata = {
    repository: "https://github.com/openclaw/agent-skills",
    revision,
    path: sourcePath,
    sha256: createHash("sha256").update(bytes).digest("hex"),
  };
  const output = `// Generated by scripts/pin-helper.mjs. Metadata only; implementation stays upstream.\nexport const helperProvenance = ${JSON.stringify(metadata, null, 2)} as const;\n`;
  const target = new URL("../src/helper-provenance.ts", import.meta.url);
  if (mode === "--check") {
    const current = readFileSync(target, "utf8");
    for (const value of Object.values(metadata)) {
      if (!current.includes(JSON.stringify(value)))
        throw new Error("Canonical helper provenance differs; regenerate metadata.");
    }
  } else writeFileSync(target, output);
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  console.error("[pin-helper] FAILED (exit 1)");
  process.exitCode = 1;
}
